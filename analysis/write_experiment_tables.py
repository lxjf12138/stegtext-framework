#!/usr/bin/env python3
"""Generate LaTeX tables from tracked aggregate data, without inference."""
from pathlib import Path
import csv

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT/'evidence/derived/experiments_20261101'
OUT = ROOT/'manuscript/sections/generated'
OUT.mkdir(exist_ok=True)


def rows(path):
    return list(csv.DictReader(path.open()))


def save(name, text):
    (OUT/(name+'.tex')).write_text('% Generated by analysis/write_experiment_tables.py.\n'+text)


recovery = rows(DATA/'RECOVERY.csv')
text = r'''\begin{table}[!t]
\centering
\caption{Prefix recovery by method family. Main and Repeats give exact/planned runs; the last two columns count successful runs with zero delivered bits or invalid UTF-8, respectively. Repeats reuse the same documents.}
\label{tab:recovery}
\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lrrrr}
\toprule
Method & Main & Repeats & \shortstack{Zero\\payload} & \shortstack{Invalid\\UTF-8}\\
\midrule
'''
for family in ('LAS','SyncPool','MWIS','Basic','Stepwise','All steganographic'):
    a=next(r for r in recovery if r['family']==family and r['cohort']=='main')
    b=next(r for r in recovery if r['family']==family and r['cohort']=='all')
    n=int(b['planned'])-int(a['planned']); e=int(b['exact'])-int(a['exact'])
    if family=='All steganographic': text += '\\midrule\n'
    label='All' if family=='All steganographic' else ('LAS (all $\\tau$)' if family=='LAS' else family)
    repeat=f'{e}/{n}' if n else '--'
    text += f"{label} & {a['exact']}/{a['planned']} & {repeat} & {b['zero_payload_exact']} & {b['invalid_utf8']}\\\\\n"
text += '\\bottomrule\n\\end{tabular}\n\\end{table}\n'
save('experiment_recovery',text)

points=rows(DATA/'MAIN_POINTS.csv')
quality=rows(DATA/'MAIN_QUALITY.csv')
# Main table (2026-11-02): one row per method and setting, both models side by
# side, following the per-method layout of the related papers. No bold: the
# filtering methods do not share the distribution target, and several
# fast-point intervals overlap. PPL is shown as the ratio to ordinary sampling,
# so no ordinary rows are needed; the dagger marks intervals that exclude one.
METHODS=[('las_imec','LAS($\\tau{=}0$)'),('adaptive_4000_imec','LAS($\\tau{=}4$)'),
         ('syncpool_imec','SyncPool'),('stepwise_imec','Stepwise'),('mwis_imec','MWIS'),('basic_imec','Basic')]
MODELS=[('llama_instruct','Llama-3.2-3B / English'),('qwen_instruct','Qwen3-4B / Chinese')]
point={(r['model'],r['top_k'],r['variant']):r for r in points}
qual={(r['model'],r['top_k'],r['variant']):r for r in quality}


def cells(model,k,variant):
    q=qual.get((model,k,variant))
    if q is None:
        return ['--']*6
    ppl=f"{float(q['ppl_ratio_to_ordinary']):.2f}"
    p=point[model,k,variant]
    significant=not float(q['ppl_ratio_ci95_low'])<=1<=float(q['ppl_ratio_ci95_high'])
    kl=float(q['kl_bits_per_body_token'])
    return [f"{float(p['native_body_bpt']):.2f}", f"{100*float(q['utilization']):.0f}",
            f"{float(p['sender_receiver_ms_per_body_token']):.1f}",
            f"{float(p['confirmed_bits_per_sender_receiver_second']):.1f}",
            ppl+('$^\\dagger$' if significant else '\\phantom{$^\\dagger$}'),
            '0' if kl==0 else f'{1000*kl:.1f}']


text=r"""\begin{table*}[!t]
\centering
\caption{Main operating points. LAS($\tau{=}0$), LAS($\tau{=}4$), and SyncPool preserve the source distribution; Stepwise, MWIS, and Basic filter it. Util.: BPT over the per-token sampler entropy; ms/tok, bit/s: sender-plus-receiver time; PPL ratio: corpus perplexity relative to ordinary sampling ($^\dagger$: 95\% interval excludes one); KL: filtering divergence in mbit per body token.}
\label{tab:main_operating_points}
\footnotesize
\setlength{\tabcolsep}{3.1pt}
\begin{tabular}{llrrrrrr@{\hspace{9pt}}rrrrrr}
\toprule
"""
text+=' & & '+' & '.join(f'\\multicolumn{{6}}{{c}}{{{label}}}' for _,label in MODELS)+'\\\\\n'
text+='\\cmidrule(lr){3-8}\\cmidrule(lr){9-14}\n'
text+='$k$ & Method & '+' & '.join(['BPT & Util.\\,\\% & ms/tok & bit/s & PPL ratio & KL']*2)+'\\\\\n'
for k in ['16','32','128','256','0']:
    text+='\\midrule\n'
    for i,(variant,label) in enumerate(METHODS):
        if k=='0' and variant=='stepwise_imec':
            continue
        row=[cells(model,k,variant) for model,_ in MODELS]
        text+=f"{('Full' if k=='0' else k) if i==0 else ''} & {label} & "+' & '.join(row[0]+row[1])+'\\\\\n'
text+='\\bottomrule\n\\end{tabular}\n\\end{table*}\n'
save('experiment_main_points',text)
